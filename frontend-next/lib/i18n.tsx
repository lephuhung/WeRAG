const dicts: Record<Locale, Partial<Record<keyof typeof en, string>>> = { en, vi };
const STORAGE_KEY = "werag_locale";

export type LocaleKey = keyof typeof en;
type I18n = {
  locale: Locale;
  /* persist=false skips the server write — used when applying the locale
   * the server itself returned, which would otherwise echo it back. */
  setLocale: (l: Locale, persist?: boolean) => void;
  /* vars fills `{name}` placeholders, e.g. t("uploadTasks.retryFailed", {count: 2}). */
  t: (k: LocaleKey, vars?: Record<string, string | number>) => string;
};
const I18nContext = createContext<I18n>({
  locale: "vi",
  setLocale: () => {},
  t: (k, vars) => {
    const raw = en[k];
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
      vars[name] === undefined ? `{${name}}` : String(vars[name]),
    );
  },
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  /* Vietnamese is the default UI language; an explicit saved choice wins. */
  const [locale, setLocaleState] = useState<Locale>("vi");

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "vi") {
      setLocaleState(saved);
      document.documentElement.lang = saved;
    } else {
      document.documentElement.lang = "vi";
    }
  }, []);

  const setLocale = useCallback((l: Locale, persist = true) => {
    setLocaleState(l);
    localStorage.setItem(STORAGE_KEY, l);
    document.documentElement.lang = l;
    /* Server copy makes the choice follow the account across devices;
     * skipped when logged out (no token) or when applying a server value. */
    if (persist && getTokens().token) {
      void updateMyPreferences({ language: l });
    }
  }, []);

  const t = (k: keyof typeof en, vars?: Record<string, string | number>) => {
    const raw = dicts[locale]?.[k] ?? (en as Record<string, string>)[k] ?? String(k);
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
      vars[name] === undefined ? `{${name}}` : String(vars[name]),
    );
  };

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext);
}
